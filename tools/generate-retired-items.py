#!/usr/bin/env python3
"""Generate stable native IDs from data/items/retired-items.json."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def render(manifest):
    ids = [entry["id"] for entry in manifest["ids"]]
    if any(type(item_id) is not int or not 1 <= item_id <= 65535 for item_id in ids):
        raise ValueError("retired IDs must be integers from 1 to 65535")
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate retired ID")
    ids.sort()
    lines = ["    " + ", ".join(map(str, ids[start:start + 8])) + "," for start in range(0, len(ids), 8)]
    return (
        "// Generated by tools/generate-retired-items.py from data/items/retired-items.json.\n"
        "// Keep item indices stable; regenerate when the canonical manifest changes.\n"
        "#ifndef TFS_RETIRED_ITEM_IDS_H\n#define TFS_RETIRED_ITEM_IDS_H\n\n"
        "#include <array>\n#include <cstdint>\n\n"
        "namespace RetiredItems {\n"
        f"constexpr std::array<uint16_t, {len(ids)}> ids = {{{{\n"
        + "\n".join(lines) + "\n}};\n}\n\n#endif\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=ROOT / "data/items/retired-items.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src/retired_item_ids.h")
    parser.add_argument("--check", action="store_true", help="fail if the generated header is stale")
    args = parser.parse_args()
    try:
        header = render(json.loads(args.manifest.read_text(encoding="utf-8")))
        if args.check:
            if not args.output.exists() or args.output.read_text(encoding="utf-8") != header:
                raise ValueError("retired item header is stale; run tools/generate-retired-items.py")
        else:
            args.output.write_text(header, encoding="utf-8", newline="\n")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
